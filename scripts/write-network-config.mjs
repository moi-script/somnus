import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Generates the Android network security config from NEXT_PUBLIC_API_URL.
 *
 * Android 9+ blocks cleartext HTTP for apps targeting SDK 28 or later, which
 * this one does. A LAN API on plain http is refused by the platform before the
 * request leaves the phone, and the app can only report "cannot reach the
 * server" - the failure looks identical to the server being down.
 *
 * Rather than blanket-enabling cleartext, the exception is derived from the
 * same .env value that gets compiled into the bundle, so the two can never
 * disagree. An https API produces a config with no exception at all.
 */
const here = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.resolve(here, '../.env');
const xmlPath = path.resolve(
  here,
  '../apps/mobile/android/app/src/main/res/xml/network_security_config.xml',
);
const manifestPath = path.resolve(
  here,
  '../apps/mobile/android/app/src/main/AndroidManifest.xml',
);

function apiHost() {
  if (!fs.existsSync(envPath)) return null;
  for (const raw of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line.startsWith('NEXT_PUBLIC_API_URL=')) continue;
    const value = line.slice('NEXT_PUBLIC_API_URL='.length).trim();
    try {
      const url = new URL(value);
      return url.protocol === 'http:' ? url.hostname : null;
    } catch {
      return null;
    }
  }
  return null;
}

const host = apiHost();

const domains = ['localhost', '10.0.2.2']; // 10.0.2.2 is the host from an emulator
if (host && !domains.includes(host)) domains.push(host);

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/write-network-config.mjs. Do not edit by hand:
     it is rewritten from NEXT_PUBLIC_API_URL on every build. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
${
  host
    ? `    <!-- The API is on plain http, so cleartext is permitted for it alone.
         Point NEXT_PUBLIC_API_URL at an https server and this block
         disappears on the next build. -->
    <domain-config cleartextTrafficPermitted="true">
${domains.map((d) => `        <domain includeSubdomains="false">${d}</domain>`).join('\n')}
    </domain-config>
`
    : '    <!-- API is https; no cleartext exception needed. -->\n'
}</network-security-config>
`;

fs.mkdirSync(path.dirname(xmlPath), { recursive: true });
fs.writeFileSync(xmlPath, xml);

// Point the manifest at it, once. Git rewrites this file with CRLF endings,
// so the match must not assume \n - an earlier version silently did nothing
// while reporting success.
const manifest = fs.readFileSync(manifestPath, 'utf8');
if (!manifest.includes('android:networkSecurityConfig')) {
  const patched = manifest.replace(
    /<application\r?\n(\s*)/,
    (_match, indent) => `<application\r\n${indent}android:networkSecurityConfig="@xml/network_security_config"\r\n${indent}`,
  );
  if (patched === manifest) {
    console.error('[net] could not patch AndroidManifest.xml - add this to <application>:');
    console.error('      android:networkSecurityConfig="@xml/network_security_config"');
    process.exit(1);
  }
  fs.writeFileSync(manifestPath, patched);
  console.log('[net] manifest now references the network security config');
}

console.log(
  host
    ? `[net] cleartext permitted for: ${domains.join(', ')}`
    : '[net] cleartext blocked everywhere (API is https or unset)',
);
